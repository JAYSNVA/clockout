import { useCallback, useEffect, useState } from "react";
import { ApiError, api, type Me } from "./api";
import { Login } from "./Login";
import { DeveloperPage } from "./Developer";
import { ManagerPage } from "./Manager";

export function App() {
  const [me, setMe] = useState<Me | null | undefined>(undefined);

  const load = useCallback(async () => {
    try {
      setMe(await api<Me>("GET", "/api/me"));
    } catch (err) {
      if (err instanceof ApiError && err.status === 401) setMe(null);
      else throw err;
    }
  }, []);

  useEffect(() => {
    void load();
  }, [load]);

  if (me === undefined) return null;
  if (me === null) return <Login onSignedIn={load} />;

  const signOut = async () => {
    await api("POST", "/api/logout");
    setMe(null);
  };

  return (
    <>
      <header className="topbar">
        <div className="brand">
          <svg width="22" height="22" viewBox="0 0 24 24" aria-hidden>
            <circle cx="12" cy="12" r="10" fill="none" stroke="currentColor" strokeWidth="1.8" />
            <path d="M12 6v6l4 2" stroke="currentColor" strokeWidth="1.8" fill="none" strokeLinecap="round" />
          </svg>
          Clockout
        </div>
        <div className="row">
          <span className="secondary small">
            {me.user.name} · {me.user.role === "manager" ? "Manager" : "Developer"}
          </span>
          <button onClick={signOut}>Sign out</button>
        </div>
      </header>
      {me.demo && <DemoBanner />}
      {me.user.role === "manager" ? <ManagerPage me={me} /> : <DeveloperPage me={me} reloadMe={load} />}
    </>
  );
}

export function DemoBanner() {
  return (
    <div className="demo-banner">
      <b>Demo data.</b> A sample team generated by <code>npm run demo</code>. Clock out here only touches the demo repos.
      Run <code>npm start</code> for your real data.
    </div>
  );
}
